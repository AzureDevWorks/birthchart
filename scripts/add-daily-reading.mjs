write('src/features/dashboard/lib/daily-reading-store.ts', [
  "import { create } from 'zustand';",
  "import { persist } from 'zustand/middleware';",
  "",
  "export interface DailyReadingPayload {",
  "  vara_note: string;",
  "  panchang_note: string;",
  "  dasha_note: string;",
  "  transit_note: string;",
  "  wear: string;",
  "  eat: string;",
  "  avoid_eating: string;",
  "  do: string[];",
  "  avoid: string[];",
  "  mantra: string;",
  "  color: string;",
  "  summary: string;",
  "}",
  "",
  "export interface DailyReadingRecord {",
  "  key: string;",
  "  date: string;",
  "  language: string;",
  "  profileHash: string;",
  "  profileName: string;",
  "  payload: DailyReadingPayload;",
  "  providerId: string;",
  "  modelId: string;",
  "  generatedAt: string;",
  "  wordCount: number;",
  "  promptVersion: string;",
  "}",
  "",
  "interface State {",
  "  records: Record<string, DailyReadingRecord>;",
  "  save: (r: DailyReadingRecord) => void;",
  "  remove: (key: string) => void;",
  "  clearAll: () => void;",
  "}",
  "",
  "const STORE_VERSION = 1;",
  "const MAX_AGE_DAYS = 60;",
  "const MAX_RECORDS = 200;",
  "",
  "function prune(records: Record<string, DailyReadingRecord>): Record<string, DailyReadingRecord> {",
  "  const cutoff = Date.now() - MAX_AGE_DAYS * 86_400_000;",
  "  const kept = Object.fromEntries(",
  "    Object.entries(records).filter(([, rec]) => {",
  "      const t = new Date(rec.generatedAt).getTime();",
  "      return Number.isFinite(t) && t >= cutoff;",
  "    })",
  "  );",
  "  const entries = Object.entries(kept);",
  "  if (entries.length > MAX_RECORDS) {",
  "    entries.sort((a, b) => new Date(b[1].generatedAt).getTime() - new Date(a[1].generatedAt).getTime());",
  "    return Object.fromEntries(entries.slice(0, MAX_RECORDS));",
  "  }",
  "  return kept;",
  "}",
  "",
  "export const useDailyReadingStore = create<State>()(",
  "  persist(",
  "    (set) => ({",
  "      records: {},",
  "      save: (r) => set((s) => ({ records: prune({ ...s.records, [r.key]: r }) })),",
  "      remove: (key) => set((s) => { const next = { ...s.records }; delete next[key]; return { records: next }; }),",
  "      clearAll: () => set({ records: {} }),",
  "    }),",
  "    { name: 'kundaliyatra-daily-reading', version: STORE_VERSION }",
  "  )",
  ");",
  "",
  "export function makeDailyReadingKey(profileHash: string, dateISO: string, lang: string): string {",
  "  return profileHash + '|' + dateISO + '|' + lang;",
  "}",
  ""
]);

// ─── 3. The hook ──────────────────────────────────────────────
write('src/features/dashboard/hooks/useDailyReading.ts', [
  "import { useEffect, useRef, useState } from 'react';",
  "import { DateTime } from 'luxon';",
  "import type { BirthData } from '@/domain/astrology/birth-data';",
  "import type { UserLocation } from '@/lib/user-location';",
  "import { gocharAdapter, type GocharAnalysis } from '@/infrastructure/astrology/gochar.adapter';",
  "import type { PanchangData } from '@/infrastructure/astrology/panchang.adapter';",
  "import { hashProfile } from '@/features/ai-reading/store';",
  "import { getAiSettingsSnapshot } from '@/features/ai-settings/store';",
  "import { countWords } from '@/features/ai-reading/markdown';",
  "import { execute } from '@/ai/runtime';",
  "import {",
  "  useDailyReadingStore,",
  "  makeDailyReadingKey,",
  "  type DailyReadingRecord,",
  "  type DailyReadingPayload,",
  "} from '../lib/daily-reading-store';",
  "",
  "export type DailyReadingState = 'idle' | 'generating' | 'ready' | 'error' | 'unavailable';",
  "",
  "export interface UseDailyReadingResult {",
  "  state: DailyReadingState;",
  "  record: DailyReadingRecord | null;",
  "  error: string | null;",
  "  regenerate: () => void;",
  "}",
  "",
  "const SITUATION_ID = 'daily-reading';",
  "const PACK_VERSION = '1.0.0';",
  "const PROMPT_VERSION = 'kundaliyatra.' + SITUATION_ID + '@' + PACK_VERSION;",
  "const inFlight = new Set<string>();",
  "",
  "function parsePayload(raw: string): DailyReadingPayload | null {",
  "  if (!raw) return null;",
  "  let candidate = raw.trim();",
  "  const fence = candidate.match(/```(?:json)?\\s*([\\s\\S]*?)```/);",
  "  if (fence) candidate = fence[1].trim();",
  "  const first = candidate.indexOf('{');",
  "  const last = candidate.lastIndexOf('}');",
  "  if (first < 0 || last <= first) return null;",
  "  candidate = candidate.slice(first, last + 1);",
  "  try {",
  "    const parsed = JSON.parse(candidate);",
  "    return {",
  "      vara_note: String(parsed.vara_note ?? ''),",
  "      panchang_note: String(parsed.panchang_note ?? ''),",
  "      dasha_note: String(parsed.dasha_note ?? ''),",
  "      transit_note: String(parsed.transit_note ?? ''),",
  "      wear: String(parsed.wear ?? ''),",
  "      eat: String(parsed.eat ?? ''),",
  "      avoid_eating: String(parsed.avoid_eating ?? ''),",
  "      do: Array.isArray(parsed.do) ? parsed.do.map(String) : [],",
  "      avoid: Array.isArray(parsed.avoid) ? parsed.avoid.map(String) : [],",
  "      mantra: String(parsed.mantra ?? ''),",
  "      color: String(parsed.color ?? ''),",
  "      summary: String(parsed.summary ?? ''),",
  "    };",
  "  } catch { return null; }",
  "}",
  "",
  "export function useDailyReading(",
  "  profile: BirthData,",
  "  kundli: any | null,",
  "  gochar: GocharAnalysis | null,",
  "  panchang: PanchangData | null,",
  "  location: UserLocation,",
  "  language: string = 'en'",
  "): UseDailyReadingResult {",
  "  const kundliRef = useRef(kundli); kundliRef.current = kundli;",
  "  const gocharRef = useRef(gochar); gocharRef.current = gochar;",
  "  const panchangRef = useRef(panchang); panchangRef.current = panchang;",
  "  const locationRef = useRef(location); locationRef.current = location;",
  "  const profileRef = useRef(profile); profileRef.current = profile;",
  "",
  "  const dateISO = DateTime.now().setZone(location.timezone).toISODate() ?? new Date().toISOString().slice(0, 10);",
  "  const profileHash = hashProfile(profile);",
  "  const cacheKey = makeDailyReadingKey(profileHash, dateISO, language);",
  "",
  "  const record = useDailyReadingStore((s) => s.records[cacheKey]) ?? null;",
  "  const save = useDailyReadingStore((s) => s.save);",
  "",
  "  const [state, setState] = useState<DailyReadingState>(record ? 'ready' : 'idle');",
  "  const [error, setError] = useState<string | null>(null);",
  "  const [regenTick, setRegenTick] = useState(0);",
  "",
  "  useEffect(() => {",
  "    const fresh = useDailyReadingStore.getState().records[cacheKey];",
  "    if (fresh && fresh.promptVersion === PROMPT_VERSION) {",
  "      setState('ready'); setError(null); return;",
  "    }",
  "    if (inFlight.has(cacheKey)) { setState('generating'); return; }",
  "",
  "    const snapshot = getAiSettingsSnapshot();",
  "    const configured = snapshot.providerOrder.filter((id) => snapshot.providers[id]?.apiKey);",
  "    if (configured.length === 0) { setState('unavailable'); return; }",
  "    const k = kundliRef.current;",
  "    if (!k) return;",
  "",
  "    inFlight.add(cacheKey);",
  "    setState('generating');",
  "    setError(null);",
  "",
  "    (async () => {",
  "      try {",
  "        const g = gocharRef.current ?? gocharAdapter.analyze(k, new Date());",
  "        const p = panchangRef.current;",
  "",
  "        const ctrl = new AbortController();",
  "        const timeoutId = setTimeout(() => ctrl.abort(), 60_000);",
  "",
  "        const res = await execute({",
  "          situationId: SITUATION_ID,",
  "          language: language as any,",
  "          sources: { kundli: k, gochar: g, panchang: p, profile: profileRef.current },",
  "          extras: { tone: 'traditional', numberOfWord: 300, language },",
  "          signal: ctrl.signal,",
  "        }).finally(() => clearTimeout(timeoutId));",
  "",
  "        if (!res.ok || !res.text) throw new Error(res.error ?? 'Generation failed');",
  "        const payload = parsePayload(res.text);",
  "        if (!payload) throw new Error('Model returned malformed JSON.');",
  "",
  "        const wordCount = countWords(",
  "          [payload.vara_note, payload.panchang_note, payload.dasha_note, payload.transit_note,",
  "           payload.wear, payload.eat, payload.avoid_eating, payload.summary,",
  "           payload.do.join(' '), payload.avoid.join(' ')].join(' ')",
  "        );",
  "",
  "        save({",
  "          key: cacheKey,",
  "          date: dateISO,",
  "          language,",
  "          profileHash,",
  "          profileName: profileRef.current.profileName,",
  "          payload,",
  "          providerId: res.providerId ?? '',",
  "          modelId: res.modelId ?? '',",
  "          generatedAt: new Date().toISOString(),",
  "          wordCount,",
  "          promptVersion: PROMPT_VERSION,",
  "        });",
  "        setState('ready');",
  "      } catch (e) {",
  "        setError((e as Error).message);",
  "        setState('error');",
  "      } finally {",
  "        inFlight.delete(cacheKey);",
  "      }",
  "    })();",
  "    // eslint-disable-next-line react-hooks/exhaustive-deps",
  "  }, [cacheKey, regenTick]);",
  "",
  "  const regenerate = () => {",
  "    useDailyReadingStore.getState().remove(cacheKey);",
  "    inFlight.delete(cacheKey);",
  "    setRegenTick((n) => n + 1);",
  "  };",
  "",
  "  return { state, record, error, regenerate };",
  "}",
  ""
]);

